export function khandaHi(id: string, total: number, isPeak: boolean): string {
  switch (id) {
    case 'bandhu':
      return total >= 88
        ? 'उत्कृष्ट व्यवसाय / स्व-अर्जित आजीविका की क्षमता (अंक ≥ 88)।'
        : isPeak
          ? 'प्रधान बंधु — स्वतंत्रता प्रिय; अपने संसाधन और व्यवसाय के लिए प्रबल।'
          : 'स्व-अर्जित धन और स्वतंत्रता का विषय।'
    case 'sevak':
      return isPeak
        ? 'प्रधान सेवक — पहचान नौकरी / सेवा से बनती है।'
        : 'सेवा / नौकरी का विषय।'
    case 'poshak':
      return isPeak
        ? 'प्रधान पोषक — दूसरों का पोषण और आर्थिक सहारा देने की क्षमता।'
        : 'पोषण / दूसरों को सहारा देने का विषय।'
    case 'ghatak':
      return total > 73
        ? 'घातक 73 से ऊपर — ऋण, गुप्त शत्रु और अति प्रदर्शन में सावधानी; जीवनशैली से मिलाएँ।'
        : isPeak
          ? 'प्रधान घातक — हानि, यात्रा-भार और परिवार के समय का संतुलन देखें।'
          : 'हानि / विघटन का विषय (परंपरा में इसे संयत रखा जाता है)।'
    default:
      return ''
  }
}

export function phaseLineHi(kind: 'stage' | 'direction' | 'ashram', id: string, isPeak: boolean): string {
  const name = NAMED_HI[id] ?? id
  if (kind === 'stage') {
    return isPeak ? 'शीर्ष जीवन-अवस्था — इस चरण में सबसे प्रबल बिंदु समर्थन।' : `${name} चरण का योग।`
  }
  if (kind === 'direction') {
    return isPeak ? 'कर्म, स्थान-परिवर्तन और व्यवसाय के लिए सर्वोत्तम वृद्धि दिशा।' : `${name} दिशा का योग।`
  }
  return isPeak ? 'सबसे प्रबल आश्रम / जीवन-चरण खंड।' : `${name} खंड का योग।`
}


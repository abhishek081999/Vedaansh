export function relativeHi(role: BhavaRole, bindus: number, topicShort: string): string {
  const strong = bindus >= 30
  const weak = bindus <= 23
  const row = REL[role]
  const key = strong ? 'strong' : weak ? 'weak' : 'mid'
  return fill(row[key], { topic: topicShort })
}

export function summaryExtraHi(
  topicShort: string,
  body: number,
  resources: number,
  struggle: number,
  support: number,
  sudden: number,
  gains: number,
): string[] {
  const lines: string[] = []
  if (gains > body && gains >= 28) {
    lines.push(fill(
      '{topic} के भीतर: लाभ (सापेक्ष भाव 11 = {gains}) देह (सापेक्ष भाव 1 = {body}) से अधिक — पुरस्कार स्वयं विषय की आधार-शक्ति से आगे निकल सकते हैं।',
      { topic: topicShort, gains, body },
    ))
  } else if (body > gains && body >= 30 && gains < 28) {
    lines.push(fill(
      '{topic} के भीतर: देह लाभ से प्रबल — क्षमता है, पर पूर्ति के लिए बेहतर काल / उपयोग चाहिए।',
      { topic: topicShort },
    ))
  }
  if (support >= 30) {
    lines.push(fill(
      'सहयोग (सापेक्ष भाव 7 = {support}) प्रबल — गुरु/साथी {topic} को स्थिर कर सकते हैं।',
      { support, topic: topicShort },
    ))
  } else if (body < 28 && support >= body) {
    lines.push(fill(
      'देह कोमल है पर सहयोग मौजूद — जब {topic} डगमगाए तब सहायता आ सकती है (“मरते-मरते बच जाओगे” का तर्क)।',
      { topic: topicShort },
    ))
  }
  if (struggle <= 23) {
    lines.push(fill(
      'संघर्ष (सापेक्ष भाव 6 = {struggle}) कम — परंपरा में बाधाएँ कम; प्रतिस्पर्धा की धार भी कम।',
      { struggle },
    ))
  } else if (struggle >= 30) {
    lines.push(fill(
      'संघर्ष (सापेक्ष भाव 6 = {struggle}) प्रबल — राजनीति/प्रतिस्पर्धा संभव; इसे ईंधन बनाएँ।',
      { struggle },
    ))
  }
  if (sudden <= 23) {
    lines.push(fill(
      'आकस्मिक क्षेत्र (सापेक्ष भाव 8 = {sudden}) शांत — झटके कम, लगने पर वापसी धीमी।',
      { sudden },
    ))
  }
  if (resources >= 30) {
    lines.push(fill(
      '{topic} के संसाधन/आय (सापेक्ष भाव 2 = {resources}) सहायक दिखते हैं।',
      { topic: topicShort, resources },
    ))
  }
  return lines
}


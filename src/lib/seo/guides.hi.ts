function mergeGuide(en: Guide, hi?: GuideHiOverlay): Guide {
  if (!hi) return en
  return {
    ...en,
    title: hi.title,
    description: hi.description,
    keywords: hi.keywords,
    toolCta: { ...en.toolCta, label: hi.toolCtaLabel },
    intro: hi.intro,
    sections: hi.sections,
    faqs: hi.faqs,
  }
}

export function getGuide(slug: string, locale: AppLocale = 'en'): Guide | undefined {
  const en = getGuideEn(slug)
  if (!en) return undefined
  return locale === 'hi' ? mergeGuide(en, GUIDES_HI[en.slug]) : en
}

export function listGuides(locale: AppLocale = 'en'): Guide[] {
  return GUIDES.map((g) => (locale === 'hi' ? mergeGuide(g, GUIDES_HI[g.slug]) : g))
}

export function getRelatedGuides(slug: string, locale: AppLocale = 'en', limit = 4): Guide[] {
  return getRelatedGuidesEn(slug, limit).map((g) =>
    locale === 'hi' ? mergeGuide(g, GUIDES_HI[g.slug]) : g,
  )
}

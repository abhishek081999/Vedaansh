function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function glossaryPairs(): [string, string][] {
  const pairs: [string, string][] = []
  for (let r = 1; r <= 12; r++) {
    const en = RASHI_NAMES[r as Rashi]
    const hi = RASHI_HI[r as Rashi]
    if (en && hi && en !== hi) pairs.push([en, hi])
  }
  for (const id of Object.keys(GRAHA_NAMES) as GrahaId[]) {
    const en = GRAHA_NAMES[id]
    const hi = GRAHA_HI[id]
    if (en && hi && en !== hi) pairs.push([en, hi])
  }
  NAKSHATRA_NAMES.forEach((en, i) => {
    const hi = NAKSHATRA_HI[i]
    if (en && hi && en !== hi) pairs.push([en, hi])
  })
  return pairs.sort((a, b) => b[0].length - a[0].length)
}

const GLOSSARY = glossaryPairs()

function swapGlossary(html: string): string {
  let out = html
  for (const [en, hi] of GLOSSARY) {
    out = out.replace(new RegExp(`(?<![A-Za-z])${escapeRegExp(en)}(?![A-Za-z])`, 'g'), hi)
  }
  return out
}

function applyPair(html: string, en: string, hi: string): string {
  if (!en || !html.includes(en)) return html
  // Short tokens must not rewrite a longer Latin word (Direct → Directional, Deva → Devanagari).
  const bounded = en.length < 12 && !/[\s<]/.test(en)
  if (!bounded) return html.split(en).join(hi)
  return html.replace(new RegExp(`(?<![A-Za-z])${escapeRegExp(en)}(?![A-Za-z])`, 'g'), hi)
}

/** Hindi dossier chrome. `lang === 'en'` returns `html` unchanged. */
export function applyChartHtmlChrome(html: string, lang: EngineLang = 'en'): string {
  if (lang !== 'hi' || !html) return html
  let out = html
  const entries = Object.entries(CHART_HTML_HI).sort((a, b) => b[0].length - a[0].length)
  for (const [en, hi] of entries) out = applyPair(out, en, hi)
  return swapGlossary(out)
}

#!/usr/bin/env node
/** Generates src/lib/engine/locale/dashamsaPractical.hi.ts from paired entries. */
import fs from 'fs'
import path from 'path'
import { buildAllEntries } from './d10p-entries.mjs'

const entries = buildAllEntries()

const root = path.resolve(import.meta.dirname, '..')
const hiPath = path.join(root, 'src/lib/engine/locale/dashamsaPractical.hi.ts')

const en = {}
const hi = {}
for (const { key, en: e, hi: h } of entries) {
  en[key] = e
  hi[key] = h
}

const enKeys = Object.keys(en).sort()
const hiKeys = Object.keys(hi).sort()
if (enKeys.join('|') !== hiKeys.join('|')) {
  const onlyEn = enKeys.filter((k) => !hi[k])
  const onlyHi = hiKeys.filter((k) => !en[k])
  console.error('KEY MISMATCH', { onlyEn: onlyEn.slice(0, 20), onlyHi: onlyHi.slice(0, 20) })
  process.exit(1)
}

const charityIds = ['Su', 'Mo', 'Ma', 'Me', 'Ju', 'Ve', 'Sa', 'Ra', 'Ke', 'Ur', 'Ne', 'Pl']
const D10P_CHARITY_HI = Object.fromEntries(charityIds.map((id) => [id, hi[`charity${id}`] ?? en[`charity${id}`]]))

const existing = fs.readFileSync(hiPath, 'utf8')
const sm = existing.match(/export const D10_SIGN_SECTORS_HI[\s\S]*?\n\}\s*\n/)
const sectorsBlock = sm ? sm[0].trim() : ''
if (!sectorsBlock) {
  console.error('Could not find D10_SIGN_SECTORS_HI block')
  process.exit(1)
}

function serializeConst(name, obj) {
  const lines = ['{']
  for (const [k, v] of Object.entries(obj)) {
    const escaped = JSON.stringify(v)
    lines.push(`  ${/^\w+$/.test(k) ? k : JSON.stringify(k)}: ${escaped},`)
  }
  lines.push('} as const')
  return `export const ${name} = ${lines.join('\n')}\n`
}

const out = `// Hindi for D10 practical layers — karma, bondage, survival, circuit, pending, combos.
// Generated by scripts/d10p-generate-locale.mjs — re-run after editing scripts/d10p-entries.mjs

${sectorsBlock}

export const D10P_CHARITY_HI: Record<string, string> = ${JSON.stringify(D10P_CHARITY_HI, null, 2)}

${serializeConst('D10P_TEXT_EN', en)}

${serializeConst('D10P_TEXT_HI', hi)}
`

fs.writeFileSync(hiPath, out)
console.log('Wrote', hiPath)
console.log('D10P_TEXT keys:', enKeys.length)
console.log('D10P_CHARITY_HI keys:', Object.keys(D10P_CHARITY_HI).length)
